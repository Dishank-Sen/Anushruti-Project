const NUMBER_NAMES = [
  'ZERO',
  'ONE',
  'TWO',
  'THREE',
  'FOUR',
  'FIVE',
  'SIX',
  'SEVEN',
  'EIGHT',
  'NINE',
  'TEN',
];
export function findOfficialSign(term: string): OfficialSign | undefined {
  const key = term.trim().toUpperCase();
  const number = NUMBER_NAMES.indexOf(key);
  return OFFICIAL_SIGNS[number >= 0 ? String(number) : key];
}
